const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'organon-extra-time-'));
const file = path.join(userData, 'compasso.json');
const output = path.join(root, 'test-output');
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
const saved = () => JSON.parse(fs.readFileSync(file, 'utf8'));
(async () => {
  const model = await import(pathToFileURL(path.join(root, 'src/model.js')));
  const state = model.seed(); const plan = model.firstPlan(); const block = plan.blocks[0];
  state.plans = [plan]; state.onboardingCompleted = true; state.settings.sound = false;
  const startedAt = Date.now();
  state.active = model.pause(model.play(state, plan, block, model.dayKey(), startedAt), startedAt).active;
  fs.writeFileSync(file, JSON.stringify(state)); fs.mkdirSync(output, { recursive: true });
  const launch = async () => {
    const options = process.env.COMPASSO_EXECUTABLE
      ? { executablePath: path.resolve(process.env.COMPASSO_EXECUTABLE), args: [`--user-data-dir=${userData}`], env }
      : { args: [root, `--user-data-dir=${userData}`], env };
    app = await electron.launch(options); return app.firstWindow();
  };
  let page = await launch();
  await page.getByRole('button', { name: 'Modo compacto', exact: true }).click();
  const plus = () => page.getByRole('button', { name: 'Adicionar minutos à aula', exact: true });
  await plus().click();
  assert.equal(await page.getByRole('button', { name: 'Adicionar 2 minutos', exact: true }).evaluate(el => el === document.activeElement), true);
  const bounds = await page.locator('.compact-extra-options button, .compact-controls button, .compact-title button').evaluateAll(elements => elements.map(el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, right: r.right, bottom: r.bottom }; }));
  bounds.forEach(r => assert(r.x >= 0 && r.y >= 0 && r.right <= 340 && r.bottom <= 112, JSON.stringify(r)));
  const windowBounds = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getBounds());
  assert.equal(windowBounds.width, 340); assert.equal(windowBounds.height, 112);
  await page.screenshot({ path: path.join(output, 'compact-extra-menu.png') });
  await page.keyboard.press('Escape'); assert.equal(await plus().getAttribute('aria-expanded'), 'false');
  assert.equal(await plus().evaluate(el => el === document.activeElement), true);
  await plus().click(); await page.locator('.compact-controls>strong').click();
  assert.equal(await plus().getAttribute('aria-expanded'), 'false');
  await plus().click(); await page.getByRole('button', { name: 'Adicionar 2 minutos', exact: true }).click();
  assert.equal(await page.locator('.compact-controls>strong').innerText(), '27:00');
  await page.getByRole('button', { name: 'Continuar', exact: true }).waitFor();
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Adicionar minutos à aula');
  await page.getByRole('button', { name: 'Voltar ao aplicativo', exact: true }).click();
  assert.match(await page.locator('.player-time').innerText(), /27:00\s*\/\s*27:00/);
  await page.waitForTimeout(300); assert.equal(saved().active.totalMs, 27 * 60000);
  await app.close(); page = await launch();
  assert.match(await page.locator('.player-time').innerText(), /27:00/);
  await page.clock.install();
  await page.getByRole('button', { name: 'Continuar aula', exact: true }).click();
  await page.getByRole('button', { name: 'Modo compacto', exact: true }).click();
  await plus().click(); await page.getByRole('button', { name: 'Adicionar 3 minutos', exact: true }).click();
  await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
  await page.clock.fastForward(31 * 60000);
  await page.locator('.timer-status').getByText('Concluído', { exact: true }).waitFor();
  await plus().click(); await page.getByRole('button', { name: 'Adicionar 5 minutos', exact: true }).click();
  assert.equal(await page.locator('.compact-controls>strong').innerText(), '05:00');
  await page.getByRole('button', { name: 'Continuar', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Voltar ao aplicativo', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { name: 'Concluir Aula 1', exact: true }).getAttribute('aria-checked'), 'false');
  await page.getByRole('button', { name: 'Iniciar Descanso', exact: true }).click();
  await page.getByRole('button', { name: 'Modo compacto', exact: true }).click();
  assert.equal(await plus().isDisabled(), true);
  await app.close(); app = null;
  const final = saved(); assert.equal(final.plans[0].blocks[0].minutes, 25);
  assert.equal(model.focusMs(final, model.dayKey(), model.dayKey()), 30 * 60000);
  console.log(`PASS: compact extra time, bounds, keyboard, dismissal, paused/running/completed lessons, break guard, normal player and restart persistence. Isolated profile: ${userData}`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (app) await app.close(); });
